import { timingSafeEqual } from "node:crypto";
import { runPipeline } from "@/server/agents/roadmap/pipeline";
import { adminClient } from "@/server/db/supabase";
import { PERSONAS } from "@/server/samples/personas";
import { fail, handleError, ok } from "@/server/http";

export const maxDuration = 300;

function authorised(request: Request) {
  const secret = process.env.SAMPLES_SECRET ?? "";
  const given = request.headers.get("x-samples-secret") ?? "";
  return secret.length >= 16 && given.length === secret.length && timingSafeEqual(Buffer.from(secret), Buffer.from(given));
}

/**
 * Regenerates one public sample roadmap by running the live agent pipeline on a persona.
 * Operator-only: requires the SAMPLES_SECRET header. POST /api/samples/generate?persona=0
 */
export async function POST(request: Request) {
  try {
    if (!authorised(request)) return fail(401, "unauthorized", "Not allowed.");
    const owner = process.env.SAMPLES_OWNER_ID;
    if (!owner) return fail(500, "no_owner", "SAMPLES_OWNER_ID is not set.");
    const index = Number(new URL(request.url).searchParams.get("persona") ?? "0");
    const persona = PERSONAS[index];
    if (!persona) return fail(400, "bad_persona", `persona must be 0–${PERSONAS.length - 1}`);

    const result = await runPipeline({
      profile: persona.profile, targetQuery: persona.targetQuery, hoursPerWeek: persona.hoursPerWeek, timelineMonths: persona.timelineMonths,
    }, () => {});

    const db = adminClient();
    await db.from("roadmaps").update({ status: "archived" }).eq("profile_id", owner).eq("is_sample", true).eq("sample_persona->>name", persona.name);
    const { data, error } = await db.from("roadmaps").insert({
      profile_id: owner, title: result.title, target: result.target,
      settings: { hoursPerWeek: persona.hoursPerWeek, timelineMonths: persona.timelineMonths },
      graph: result.graph, trace: result.trace, is_sample: true,
      sample_persona: { name: persona.name, background: persona.background, matches: result.matches.slice(0, 5).map((m) => ({ title: m.title, match: m.match })) },
    }).select("id").single();
    if (error) throw error;
    await db.from("roadmap_revisions").insert({ roadmap_id: data.id, profile_id: owner, version: 1, graph: result.graph, note: "Generated by the roadmap agent" });
    return ok({ id: data.id, persona: persona.name, target: result.target.title, steps: result.trace.map((s) => `${s.agent}: ${s.status} ${s.ms}ms ${s.model ?? ""}`) });
  } catch (error) {
    return handleError(error, "samples/generate");
  }
}
