import { z } from "zod";
import { runPipeline, type PipelineEvent } from "@/server/agents/roadmap/pipeline";
import { recordActivity } from "@/server/services/activity";
import { AIBusyError } from "@/server/ai/groq";
import { enforceQuota, fail, handleError, readJSON, requireUser } from "@/server/http";

export const maxDuration = 120;

const bodySchema = z.object({
  targetCode: z.string().max(12).optional(),
  targetQuery: z.string().trim().max(80).optional(),
  hoursPerWeek: z.coerce.number().min(2).max(60).optional(),
  timelineMonths: z.coerce.number().int().min(1).max(24).optional(),
  focus: z.string().trim().max(400).optional(),
  fresh: z.boolean().optional(),
});

/** Streams the agent's progress as NDJSON, then saves the roadmap. */
export async function POST(request: Request) {
  try {
    const session = await requireUser();
    const { supabase, user } = session;
    const parsed = bodySchema.safeParse(await readJSON(request));
    if (!parsed.success) return fail(400, "invalid", "Check the roadmap settings.");
    await enforceQuota(session, "roadmap", 8);

    const { data: profile, error } = await supabase.from("profiles").select("*").eq("id", user.id).single();
    if (error) throw error;
    const body = parsed.data;
    const hoursPerWeek = body.hoursPerWeek ?? profile.goals?.hoursPerWeek ?? 10;
    const timelineMonths = body.timelineMonths ?? profile.goals?.timelineMonths ?? 6;

    const encoder = new TextEncoder();
    const stream = new ReadableStream({
      async start(controller) {
        const send = (event: PipelineEvent | Record<string, unknown>) => controller.enqueue(encoder.encode(`${JSON.stringify(event)}\n`));
        try {
          const result = await runPipeline({
            profile, targetCode: body.targetCode, targetQuery: body.targetQuery, hoursPerWeek, timelineMonths, focus: body.focus,
            reuseAnalysis: !body.fresh,
          }, (event) => { if (event.type === "step") send(event); });

          const { data: saved, error: saveError } = await supabase.from("roadmaps").insert({
            profile_id: user.id,
            title: result.title,
            target: result.target,
            settings: { hoursPerWeek, timelineMonths, focus: body.focus ?? null },
            graph: result.graph,
            trace: result.trace,
          }).select("id").single();
          if (saveError) throw saveError;

          await Promise.all([
            supabase.from("roadmap_revisions").insert({ roadmap_id: saved.id, profile_id: user.id, version: 1, graph: result.graph, note: "Generated by the roadmap agent" }),
            supabase.from("profiles").update({ onet_vector: result.vector, analysis: result.analysis }).eq("id", user.id),
            recordActivity(user.id, "roadmap_generated", { roadmapId: saved.id }),
          ]);
          send({ type: "saved", id: saved.id });
        } catch (err) {
          const message = err instanceof AIBusyError ? err.message : "The agent couldn't finish this roadmap. Please try again.";
          if (!(err instanceof AIBusyError)) console.error("[roadmap/generate]", err);
          send({ type: "error", message });
        } finally {
          controller.close();
        }
      },
    });

    return new Response(stream, { headers: { "Content-Type": "application/x-ndjson; charset=utf-8", "Cache-Control": "no-store" } });
  } catch (error) {
    return handleError(error, "roadmap/generate");
  }
}
